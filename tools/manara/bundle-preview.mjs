// Builds ONE self-contained preview of the landing page:  node tools/manara/bundle-preview.mjs
//   site/manara/index.html  →  site/manara/preview/landing.html
// It inlines css/base.css, css/home.css, js/core.js, js/home.js and the logo (favicon), so the file can be opened or rendered on its own
// (no local requests at all). Links to the other pages become '../mission.html' etc. (the preview lives one folder down), including the
// links core.js renders into the nav and footer at run time (a tiny inline fixer rewrites those). No dependencies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SITE = path.join(ROOT, 'site/manara');
const read = f => fs.readFileSync(path.join(SITE, f), 'utf8');
const noClose = s => s.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

let html = read('index.html');
const must = (re, what) => { if (!re.test(html)) throw new Error('index.html changed: cannot find ' + what); };

// styles
must(/<link rel="stylesheet" href="css\/base\.css">/, 'base.css link');
must(/<link rel="stylesheet" href="css\/home\.css">/, 'home.css link');
html = html.replace('<link rel="stylesheet" href="css/base.css">', () => '<style>\n' + read('css/base.css') + '\n</style>');
html = html.replace('<link rel="stylesheet" href="css/home.css">', () => '<style>\n' + read('css/home.css') + '\n</style>');

// favicon → data URI (the logo)
must(/<link rel="icon" href="assets\/logo\.svg" type="image\/svg\+xml">/, 'favicon link');
const logo = fs.readFileSync(path.join(SITE, 'assets/logo.svg'));
html = html.replace('<link rel="icon" href="assets/logo.svg" type="image/svg+xml">', () => '<link rel="icon" href="data:image/svg+xml;base64,' + logo.toString('base64') + '" type="image/svg+xml">');

// scripts: the page uses <script defer>; inline scripts ignore defer, so they go at the end of <body> in the same order
must(/<script src="js\/core\.js" defer><\/script>/, 'core.js script');
must(/<script src="js\/home\.js" defer><\/script>/, 'home.js script');
html = html.replace('<script src="js/core.js" defer></script>\n', '').replace('<script src="js/home.js" defer></script>\n', '');
const fixer = `(function(){
  // the preview sits in site/manara/preview/, the other pages one folder up
  var re=/^(index|mission|detect|alert|build|pitch|report|poster|404)\\.html([?#].*)?$/;
  function fix(root){(root.querySelectorAll?root:document).querySelectorAll('a[href]').forEach(function(a){var h=a.getAttribute('href');if(re.test(h))a.setAttribute('href','../'+h)})}
  function watch(sel){var n=document.querySelector(sel);if(n)new MutationObserver(function(){fix(n)}).observe(n,{childList:true,subtree:true})}
  watch('[data-nav]');watch('[data-footer]');
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',function(){fix(document)});else fix(document);
  window.addEventListener('load',function(){fix(document)});
})();`;
const inline = '<script>\n' + noClose(read('js/core.js')) + '\n</script>\n<script>\n' + noClose(fixer) + '\n</script>\n<script>\n' + noClose(read('js/home.js')) + '\n</script>\n';
must(/<\/body>/, '</body>');
html = html.replace('</body>', () => inline + '</body>');

// static links to the other pages
html = html.replace(/href="((?:index|mission|detect|alert|build|pitch|report|poster)\.html(?:[#?][^"]*)?)"/g, 'href="../$1"');

html = html.replace('<!doctype html>', '<!doctype html>\n<!-- GENERATED by tools/manara/bundle-preview.mjs from site/manara/index.html: do not edit. Self-contained preview (links go to ../*.html). -->');

const out = path.join(SITE, 'preview/landing.html');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html);
const external = (html.match(/(?:src|href)="(?!https?:|data:|#|\.\.\/|mailto:)[^"]+"/g) || []);
console.log(`wrote ${path.relative(ROOT, out)}  (${(Buffer.byteLength(html) / 1024).toFixed(0)} kB)`);
if (external.length) { console.log('WARNING relative references left in the bundle:', external.join(', ')); process.exitCode = 1; }
