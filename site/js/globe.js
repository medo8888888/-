  function exposeToAT(canvas) {
    var hidden = canvas.parentElement && canvas.parentElement.closest('[aria-hidden="true"]');
    if (!hidden) return;
    var path = [];
    for (var el = canvas; el && el !== hidden; el = el.parentElement) path.push(el);
    hidden.removeAttribute('aria-hidden');
    for (var p = canvas.parentElement; p; p = p.parentElement) {
      Array.prototype.forEach.call(p.children, function (ch) {
        if (path.indexOf(ch) < 0 && !ch.hasAttribute('data-globe-ui')) ch.setAttribute('aria-hidden', 'true');
      });
      if (p === hidden) break;
    }
  }

