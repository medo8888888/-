    /* ---------- hit testing (only the five countries) ---------- */
    function unproject(sx, sy) {
      var x = (sx - cx) / R, y = -(sy - cy) / R, d = x * x + y * y;
      if (d > 1) return null;
      var z = Math.sqrt(1 - d);
      var X = m[0] * x + m[3] * y + m[6] * z, Y = m[1] * x + m[4] * y + m[7] * z, Z = m[2] * x + m[5] * y + m[8] * z;
      return [Math.atan2(X, Z) / DEG, Math.asin(clamp(Y, -1, 1)) / DEG];
    }
    function countryAtLL(lon, lat) {
      var cs = M.countries;
      for (var i = 0; i < cs.length; i++) {
        var c = cs[i], b = c.bbox;
        if (lat < b[1] || lat > b[3] || lon < b[0] || lon > b[2]) continue;
        var ins = false;
        for (var r = 0; r < c.ringsLL.length; r++) if (inRing(lon, lat, c.ringsLL[r])) ins = !ins;
        if (ins) return i;
      }
      return -1;
    }
    function countryAt(sx, sy) {
      if (!M.full) return -1;
      var ll = unproject(sx, sy);
      if (!ll) return -1;
      var hit = countryAtLL(ll[0], ll[1]);
      if (hit >= 0) return hit;
      // Palestine is tiny: its label / anchor count as a target too
      var c = M.byIso.PS;
      if (c) {
        var tol = Math.max(10, R * 0.03), a = project(c.v), l = project(c.lv);
        if (a[2] > 0.1 && Math.hypot(a[0] - sx, a[1] - sy) < tol) return c.i;
        if (l[2] > 0.1 && Math.abs(l[0] - sx) < tol * 2.2 && Math.abs(l[1] - sy) < tol) return c.i;
      }
      return -1;
    }

    /* ---------- camera ---------- */
    function flyTo(lon, lat, dur) {
      var dl = wrapLon(lon - view.lon);
      anim = { lon0: view.lon, lat0: view.lat, dl: dl, dlat: clamp(lat, -60, 70) - view.lat, t0: now(), dur: reduce ? 0 : (dur || clamp(500 + Math.abs(dl) * 8, 650, 1500)) };
      vel = 0; velLat = 0; idleUntil = now() + 5000;
      wake();
    }
    function flyHome(announce) {
      selected = -1; focusC = -1; setTip(-1);
      flyTo(HOME.lon, HOME.lat, 1100);
      if (announce) say(UI.back + ' — ' + M.labels.hqTitle + ': ' + M.labels.hqText);
    }
    function describe(c) { return c.ar + (c.hq ? ' — ' + M.labels.hqTitle + ': ' + M.labels.hqText : '') + ' — ' + UI.boardTag; }
    function flyToIso(iso, announce) {
      var c = M.byIso[iso];
      if (!c) { flyHome(announce); return; }
      flyTo(c.lon, c.lat);
      selected = c.i; hover = -1;
      setTip(c.i, 'anchor');
      if (announce) say(describe(c));
    }
    function say(msg) { live.textContent = ''; setTimeout(function () { live.textContent = msg; }, 30); }

    /* ---------- loop ---------- */
    function step(dt, tNow) {
      if (anim) {
        var k = anim.dur ? clamp((tNow - anim.t0) / anim.dur, 0, 1) : 1, e = easeInOut(k);
        view.lon = wrapLon(anim.lon0 + anim.dl * e); view.lat = anim.lat0 + anim.dlat * e;
        if (k >= 1) anim = null;
        return;
      }
      if (drag) return;
      vel *= Math.pow(0.94, dt / 16.7); velLat *= Math.pow(0.92, dt / 16.7);
      view.lon = wrapLon(view.lon + vel * dt);
      view.lat = clamp(view.lat + velLat * dt, -60, 70);
      var holding = hover >= 0 || selected >= 0 || focusC >= 0 || tNow < idleUntil;
      if (!holding && !reduce && Math.abs(vel) < 0.002) { // drift home with a gentle sway
        var tl = HOME.lon + Math.sin(tNow / 5200) * 5, kk = Math.min(1, dt / 2400);
        view.lon = wrapLon(view.lon + wrapLon(tl - view.lon) * kk);
        view.lat += (HOME.lat - view.lat) * kk;
      }
    }
    function loop(ts) {
      raf = 0;
      if (!running) return;
      var dt = last ? Math.min(64, ts - last) : 16.7; last = ts;
      step(dt, now());
      draw((ts - t0) / 1000);
      raf = requestAnimationFrame(loop);
    }
    function wake() {
      if (!W || running) return;
      if (reduce) { // static frames; camera moves are instant
        if (anim) step(16, now() + 1e6);
        draw(0);
        return;
      }
      if (!visible || document.hidden) return;
      running = true; last = 0; raf = requestAnimationFrame(loop);
    }
    function sleep() { running = false; if (raf) cancelAnimationFrame(raf); raf = 0; }
    function redraw() { if (!running) draw(reduce ? 0 : (now() - t0) / 1000); }

    /* ---------- pointer ---------- */
    function local(e) { var r = canvas.getBoundingClientRect(); return [e.clientX - r.left, e.clientY - r.top]; }
    function hoverTest() {
      var ci = countryAt(pointer.x - offX, pointer.y - offY);
      if (ci !== hover) {
        hover = ci;
        canvas.classList.toggle('is-hovering', ci >= 0);
        if (ci >= 0) setTip(ci, 'pointer'); else if (selected >= 0) setTip(selected, 'anchor'); else setTip(-1);
        redraw();
      }
      if (ci >= 0 && !running) placeTip();
    }
    canvas.addEventListener('pointerdown', function (e) {
      if (e.button > 0) return;
      var p = local(e);
      drag = { id: e.pointerId, x: p[0], y: p[1], lx: p[0], ly: p[1], lt: now(), moved: false, lon: view.lon, lat: view.lat };
      anim = null; vel = 0; velLat = 0;
      if (e.pointerType === 'mouse') { try { canvas.setPointerCapture(e.pointerId); } catch (err) { /* ignore */ } }
    });
    canvas.addEventListener('pointermove', function (e) {
      var p = local(e);
      pointer.x = p[0] + offX; pointer.y = p[1] + offY; pointer.in = true;
      if (drag && drag.id === e.pointerId) {
        var dx = p[0] - drag.x, dy = p[1] - drag.y;
        if (!drag.moved && Math.hypot(dx, dy) > 4) {
          drag.moved = true; canvas.classList.add('is-dragging');
          if (e.pointerType !== 'mouse') { try { canvas.setPointerCapture(e.pointerId); } catch (err) { /* ignore */ } }
          hover = -1; setTip(-1);
        }
        if (!drag.moved) return;
        var k = 1 / R / DEG * 0.9;
        view.lon = wrapLon(drag.lon - dx * k);
        if (e.pointerType !== 'touch') view.lat = clamp(drag.lat + dy * k, -60, 70);
        var t = now(), dtm = Math.max(1, t - drag.lt);
        vel = vel * 0.6 + (-(p[0] - drag.lx) * k / dtm) * 0.4;
        velLat = e.pointerType === 'touch' ? 0 : velLat * 0.6 + ((p[1] - drag.ly) * k / dtm) * 0.4;
        drag.lx = p[0]; drag.ly = p[1]; drag.lt = t;
        idleUntil = t + 3000;
        redraw();
        return;
      }
      if (e.pointerType === 'mouse') hoverTest();
    });
    function endDrag(e, cancelled) {
      if (!drag || drag.id !== e.pointerId) return;
      var d = drag; drag = null;
      canvas.classList.remove('is-dragging');
      if (reduce || now() - d.lt > 120) { vel = 0; velLat = 0; }
      vel = clamp(vel, -0.5, 0.5); velLat = clamp(velLat, -0.25, 0.25);
      idleUntil = now() + 3500;
      if (cancelled || d.moved) { wake(); return; }
      var p = local(e), t = now();
      if (t - lastTap.t < 340 && Math.hypot(p[0] - lastTap.x, p[1] - lastTap.y) < 30) { lastTap.t = 0; flyHome(true); return; }
      lastTap = { t: t, x: p[0], y: p[1] };
      var ci = countryAt(p[0], p[1]);
      if (e.pointerType === 'mouse') selected = ci;
      else { selected = ci === selected ? -1 : ci; if (selected >= 0) setTip(selected, 'anchor'); else setTip(-1); }
      if (selected >= 0) { idleUntil = t + 5000; say(describe(M.countries[selected])); }
      redraw();
    }
    canvas.addEventListener('pointerup', function (e) { endDrag(e, false); });
    canvas.addEventListener('pointercancel', function (e) { endDrag(e, true); });
    canvas.addEventListener('pointerleave', function (e) {
      if (e.pointerType !== 'mouse') return;
      pointer.in = false;
      if (hover >= 0) { hover = -1; canvas.classList.remove('is-hovering'); if (selected < 0) setTip(-1); else setTip(selected, 'anchor'); redraw(); }
    });
    canvas.addEventListener('dblclick', function (e) { e.preventDefault(); });
    canvas.addEventListener('contextmenu', function () { drag = null; canvas.classList.remove('is-dragging'); });

