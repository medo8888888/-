  function toXYZ(lon, lat, out, o) {
    var cl = Math.cos(lat * DEG);
    out[o] = cl * Math.sin(lon * DEG); out[o + 1] = Math.sin(lat * DEG); out[o + 2] = cl * Math.cos(lon * DEG);
  }
  function vec(lon, lat) { var v = [0, 0, 0]; toXYZ(lon, lat, v, 0); return v; }
  function inRing(lon, lat, r) { // r: flat [lon,lat,…]
    var ins = false, n = r.length;
    for (var i = 0, j = n - 2; i < n; j = i, i += 2) {
      var yi = r[i + 1], yj = r[j + 1];
      if ((yi > lat) !== (yj > lat) && lon < (r[j] - r[i]) * (lat - yi) / (yj - yi) + r[i]) ins = !ins;
    }
    return ins;
  }
  function angDist(a, b) { return Math.acos(clamp(a[0] * b[0] + a[1] * b[1] + a[2] * b[2], -1, 1)); }
  function fibXYZ(k, n, out, o) {
    var y = 1 - (k / (n - 1)) * 2, r = Math.sqrt(Math.max(0, 1 - y * y)), th = GA * k;
    out[o] = Math.cos(th) * r; out[o + 1] = y; out[o + 2] = Math.sin(th) * r;
  }
  function fibField(n, deltas) {
    var o = new Float32Array(deltas.length * 3), k = 0;
    for (var i = 0; i < deltas.length; i++) { k += deltas[i]; fibXYZ(k, n, o, 3 * i); }
    return o;
  }

