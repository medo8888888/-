        lon: lon, lat: lat, v: vec(lon, lat), lv: vec(la[0], la[1]), leader: c.iso2 === 'PS',
        ringsLL: ringsLL, ringsXYZ: ringsXYZ,
        dots: fibField(W.fine, c.d || []), nd: (c.d || []).length
